CREATE TABLE USERS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FIRST_NAME VARCHAR2(100) NOT NULL,
    LAST_NAME VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(150) UNIQUE NOT NULL,
    PASSWORD_HASH VARCHAR2(255) NOT NULL,
    PHONE_NUMBER VARCHAR2(20),
    ACCOUNT_STATUS VARCHAR2(30) NOT NULL,
    EMAIL_VERIFIED NUMBER(1) DEFAULT 0 NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT chk_email_verified CHECK (EMAIL_VERIFIED IN (0, 1)),
    CONSTRAINT chk_account_status CHECK (ACCOUNT_STATUS IN ('ACTIVE', 'INACTIVE', 'LOCKED', 'PENDING_VERIFICATION'))
);
